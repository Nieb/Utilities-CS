
namespace Utility;
internal static partial class QUAT {
    //##########################################################################################################################################################
    //##########################################################################################################################################################
    [In(line)] internal static float dot(quat A)         => A.x*A.x + A.y*A.y + A.z*A.z + A.w*A.w;
    [In(line)] internal static float dot(quat A, quat B) => A.x*B.x + A.y*B.y + A.z*B.z + A.w*B.w;

    //##########################################################################################################################################################
    //##########################################################################################################################################################
    [In(line)] internal static float length(quat A) => sqrt(A.x*A.x + A.y*A.y + A.z*A.z + A.w*A.w);

    //##########################################################################################################################################################
    //##########################################################################################################################################################
    [In(line)] internal static quat normalize(quat A) => A / sqrt(A.x*A.x + A.y*A.y + A.z*A.z + A.w*A.w);

    //==========================================================================================================================================================
    //
    //  Normalize abusively interpolated Quaternions.  :(
    //
    [In(line)] internal static quat normalize_safe(quat A) {float Len = sqrt(A.x*A.x + A.y*A.y + A.z*A.z + A.w*A.w);  return (Len < EPS5) ? new() : A/Len;}

    //##########################################################################################################################################################
    //##########################################################################################################################################################
    //
    //  NOTE:  Probably shouldn't use this directly.  You've been warned.
    //
    [In(line)] internal static quat Lerp(float w, quat A, quat B) => A*(1f-w) + B*(w);

    //==========================================================================================================================================================
    internal static quat Nlerp(float w, quat A, quat B) {
        float CosT = dot(A,B);

        //  Avoid double-cover trap, use shortest path:
        if (CosT < 0f) B = -B;

        return normalize_safe(Lerp(w, A,B));
    }

    //==========================================================================================================================================================
    internal static quat Slerp(float w, quat A, quat B) {
        float CosT = dot(A,B);

        //  Avoid double-cover trap, use shortest path:
        if (CosT < 0f) {
            B    = -B;
            CosT = -CosT;
        }

        //  Avoid Colinear trap & precision drift:
        if (CosT > 0.9995f) return normalize_safe(Lerp(w, A,B));

        float Theta = acos(CosT);
        float SinT  = sin(Theta);

        return A * (sin(Theta * (1f-w)) / SinT)
             + B * (sin(Theta *     w ) / SinT);
    }

    //##########################################################################################################################################################
    //##########################################################################################################################################################
}
