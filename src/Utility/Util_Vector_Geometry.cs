
namespace Utility;
internal static partial class VEC_Geometry {
    //##########################################################################################################################################################
    //##########################################################################################################################################################
    [In(line)] internal static v1 Area(v1 Size_x, v1 Size_y) => (Size_x * Size_y);
    [In(line)] internal static v1 Area(v2 Size)              => (Size.x * Size.y);

    [In(line)] internal static i1 Area(i1 Size_x, i1 Size_y) => (Size_x * Size_y);
    [In(line)] internal static i1 Area(i2 Size)              => (Size.x * Size.y);

    //----------------------------------------------------------------------------------------------------------------------------------------------------------
    [In(line)] internal static v1 Volume(v1 Size_x, v1 Size_y, v1 Size_z) => (Size_x * Size_y * Size_z);
    [In(line)] internal static v1 Volume(v3 Size)                         => (Size.x * Size.y * Size.z);

    [In(line)] internal static i1 Volume(i1 Size_x, i1 Size_y, i1 Size_z) => (Size_x * Size_y * Size_z);
    [In(line)] internal static i1 Volume(i3 Size)                         => (Size.x * Size.y * Size.z);

    //##########################################################################################################################################################
    //##########################################################################################################################################################
    [In(line)] internal static v1 Circle_SurfaceArea(v1 Rds = 1f) => PI * (Rds*Rds);

    //##########################################################################################################################################################
    //##########################################################################################################################################################
  //[In(line)] internal static v1 Cylinder_SurfaceA__a(v1 Rds = 1f, v1 Height = 2f) => (PI2 * (Rds*Rds)) + (PI2 * Rds * Height);
    [In(line)] internal static v1 Cylinder_SurfaceArea(v1 Rds = 1f, v1 Height = 2f) => PI2 *  Rds      * (Rds + Height);
    [In(line)] internal static v1 Cylinder_Volume     (v1 Rds = 1f, v1 Height = 2f) => PI  * (Rds*Rds) *        Height;

    //==========================================================================================================================================================
    [In(line)] internal static v1 Sphere_SurfaceArea(v1 Rds = 1f) => PI4   * (Rds*Rds);
    [In(line)] internal static v1 Sphere_Volume     (v1 Rds = 1f) => PI_43 * (Rds*Rds);

    //##########################################################################################################################################################
    //##########################################################################################################################################################
}
